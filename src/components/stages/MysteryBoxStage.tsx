/** A fabricated ticker of other players winning top items (the fake-live-feed rig). */
function LiveFeed({ pool, price, perMinute }: { pool: ReelPoolEntry[]; price: number; perMinute: number }) {
  const [entries, setEntries] = useState<{ id: number; name: string; item: CatalogItem }[]>([]);
  const top = useMemo(() => pool.filter((p) => p.item.realized >= 5 * price).map((p) => p.item), [pool, price]);
  useEffect(() => {
    if (!top.length) return;
    let n = 0;
    const push = () => {
      const w = top.map((t) => Math.sqrt(t.realized));
      const sum = w.reduce((a, b) => a + b, 0);
      let u = Math.random() * sum;
      let item = top[top.length - 1];
      for (let i = 0; i < top.length; i++) {
        u -= w[i];
        if (u <= 0) {
          item = top[i];
          break;
        }
      }
      setEntries((e) => [{ id: ++n, name: `Player${Math.floor(100 + Math.random() * 900)}`, item }, ...e].slice(0, 8));
    };
    push();
    const t = setInterval(push, Math.max(400, 60000 / Math.max(0.1, perMinute)));
    return () => clearInterval(t);
  }, [top, perMinute]);
  return (
    <div className="flex items-center gap-2 overflow-hidden rounded-xl border border-line bg-surface px-3 py-2">
      <span className="flex shrink-0 items-center gap-1 text-[11px] font-semibold uppercase tracking-wide text-bad">
        <span className="inline-block h-2 w-2 animate-pulse rounded-full bg-bad" /> Live drops
        <Info>This feed is generated by the fabricated-live-feed rig: bots &ldquo;winning&rdquo; top items at a rate that has nothing to do with the odds.</Info>
      </span>
      <div className="flex min-w-0 flex-1 gap-2 overflow-hidden">
        {entries.map((e) => (
          <span key={e.id} className="chip animate-slide shrink-0">
            <ItemTile item={e.item} size={18} /> {e.name} won {e.item.name.split(",")[0]} · {money(e.item.retail)}
          </span>
        ))}
      </div>
    </div>
  );
}

/** Mounts its child flying in from the centre of `origin` (the box or the reel) to its own slot. */
function FlyIn({ origin, children, className = "" }: { origin: RefObject<HTMLDivElement | null>; children: ReactNode; className?: string }) {
  const ref = useRef<HTMLDivElement>(null);
  useLayoutEffect(() => {
    const el = ref.current;
    const o = origin.current;
    if (!el) return;
    if (o) {
      const a = o.getBoundingClientRect();
      const b = el.getBoundingClientRect();
      el.style.setProperty("--dx", `${a.left + a.width / 2 - (b.left + b.width / 2)}px`);
      el.style.setProperty("--dy", `${a.top + a.height / 2 - (b.top + b.height / 2)}px`);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);
  return (
    <div ref={ref} className={`animate-fly ${className}`}>
      {children}
    </div>
  );
}

function Countdown({ minutes }: { minutes: number }) {
  const [left, setLeft] = useState(minutes * 60);
  useEffect(() => {
    const t = setInterval(() => setLeft((s) => (s <= 1 ? minutes * 60 : s - 1)), 1000);
    return () => clearInterval(t);
  }, [minutes]);
  const m = Math.floor(left / 60);
  const s = left % 60;
  return (
    <span className="font-mono tabular-nums">
      {m}:{s.toString().padStart(2, "0")}
    </span>
  );
}

function Viewers({ base }: { base: number }) {
  const [n, setN] = useState(base);
  useEffect(() => {
    const t = setInterval(() => setN(Math.max(1, base + Math.round((Math.random() - 0.5) * Math.max(2, base * 0.15)))), 4000);
    return () => clearInterval(t);
  }, [base]);
  return <>{num(n)}</>;
}

