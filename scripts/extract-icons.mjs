// Extracts the SVG bodies we use from the installed Iconify JSON sets into a small generated module,
// so the app ships only the icons it needs and works offline. Run: node scripts/extract-icons.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const sets = {
  fluent: require("@iconify-json/fluent-emoji-flat/icons.json"),
  ph: require("@iconify-json/ph/icons.json"),
};
const want = {
  fluent: ["watch","handbag","gem-stone","ring","high-heeled-shoe","running-shoe","crown","sunglasses","lipstick",
    "wrapped-gift","package","money-bag","trophy","necktie","top-hat","dress","purse","briefcase","clutch-bag",
    "nail-polish","womans-boot","coat","scarf","gloves","ticket","coin","dollar-banknote","sparkles","star",
    "lotion-bottle","bottle-with-popping-cork","camera","mobile-phone","laptop","headphone","video-game","game-die",
    "slot-machine","locked","key","shield","magnifying-glass-tilted-left","bar-chart","robot","bust-in-silhouette",
    "busts-in-silhouette","fire","large-blue-diamond","hiking-boot","flat-shoe","admission-tickets","alarm-clock",
    "glowing-star","locked-with-key","chart-increasing","chart-decreasing","clipboard","hourglass-done","detective",
    "balance-scale","bank","credit-card","shopping-bags","shopping-cart","label","bookmark-tabs","test-tube","dna",
    "gear","wrench","bell","hundred-points","party-popper","warning","check-mark-button","cross-mark","information","light-bulb","compass","stopwatch"],
  ph: ["sliders-horizontal","play","stop","download-simple","upload-simple","copy","trash","eye","book-open-text","list",
    "table","arrow-right","check","x-circle","warning","info","sparkle","trophy","ticket","wallet","bank","receipt",
    "scales","detective","bug","shield-check","dice-five","shuffle","lock-key","key","seal-check","chart-bar",
    "chart-line-up","robot","users-three","user","flask","gauge","gift","package","coins","diamond","handbag","watch",
    "sneaker","crown-simple","house","folders","clock-counter-clockwise","git-branch","plus","minus","caret-down",
    "caret-right","funnel","magnifying-glass","file-text","file-code","hash","cube","stack","target","lightning","timer","gear","gear-six","question","x","arrow-counter-clockwise","arrows-clockwise","fast-forward","truck","hand-coins","crown","calendar-check","calendar-blank","medal","confetti","play-circle","caret-left","storefront","piggy-bank","money","arrow-up-right","arrow-down-right","equals","users","skull","sun","fire","arrow-left","sliders"],
};
const out = {};
let missing = [];
for (const [k, names] of Object.entries(want)) {
  const set = sets[k];
  for (const n of names) {
    let d = set.icons[n];
    if (!d && set.aliases && set.aliases[n]) d = set.icons[set.aliases[n].parent];
    if (!d) { missing.push(`${k}:${n}`); continue; }
    out[`${k}:${n}`] = { body: d.body, w: d.width || set.width || 24, h: d.height || set.height || 24 };
  }
}
const ts = `// Generated by scripts/extract-icons.mjs. Do not edit.\n// Sources: Fluent Emoji Flat (MIT, Microsoft) and Phosphor (MIT) via Iconify JSON packages.\nexport type IconDef = { body: string; w: number; h: number };\nexport const ICONS: Record<string, IconDef> = ${JSON.stringify(out)};\n`;
writeFileSync(new URL("../src/lib/icons.generated.ts", import.meta.url), ts);
console.log(`wrote ${Object.keys(out).length} icons; missing: ${missing.join(", ") || "none"}`);
